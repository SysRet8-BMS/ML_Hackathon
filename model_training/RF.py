RANDOM_STATE = 42
MODEL_PARAMS = {
    'n_estimators': 40,
    'max_depth': 14,
    'min_samples_split': 10,
    'min_samples_leaf': 20,
    'max_features': 'sqrt',
    'class_weight': 'balanced_subsample',
    'max_samples': 0.2,
    'bootstrap': True,
    'n_jobs': -1
}

def make_model(seed=RANDOM_STATE):
    return RandomForestClassifier(**MODEL_PARAMS, random_state=seed)

