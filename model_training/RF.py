# 6. Common evaluation function: candidate-level metrics and observation-level Top-1.
def evaluate_predictions(frame, probabilities):
    probabilities = np.asarray(probabilities, dtype=np.float64)
    y = frame[TARGET].to_numpy(dtype=np.uint8)
    if len(probabilities) != len(frame):
        raise ValueError('Probability count does not match candidate rows.')
    if not np.isfinite(probabilities).all():
        raise ValueError('Predicted probabilities contain NaN or infinity.')

    pred = (probabilities >= 0.5).astype(np.uint8)
    tn, fp, fn, tp = confusion_matrix(y, pred, labels=[0, 1]).ravel()
    metrics = {
        'candidate_rows': int(len(frame)),
        'candidate_positive_rate': float(y.mean()),
        'candidate_accuracy': float(accuracy_score(y, pred)),
        'candidate_precision': float(precision_score(y, pred, zero_division=0)),
        'candidate_recall': float(recall_score(y, pred, zero_division=0)),
        'candidate_f1': float(f1_score(y, pred, zero_division=0)),
        'candidate_macro_f1': float(f1_score(y, pred, average='macro', zero_division=0)),
        'candidate_roc_auc': float(roc_auc_score(y, probabilities)),
        'candidate_pr_auc': float(average_precision_score(y, probabilities)),
        'candidate_log_loss': float(log_loss(y, np.column_stack([1-probabilities, probabilities]), labels=[0, 1])),
        'tn': int(tn), 'fp': int(fp), 'fn': int(fn), 'tp': int(tp)
    }

    # For each GPS observation, select the candidate with the highest RF probability.
    # Deterministic tie-break: lower candidate_rank, then lower arc_id.
    ranked = frame[[GROUP, OBSERVATION, ARC, 'candidate_rank', TARGET]].copy()
    ranked['probability'] = probabilities
    ranked = ranked.sort_values(
        [GROUP, OBSERVATION, 'probability', 'candidate_rank', ARC],
        ascending=[True, True, False, True, True], kind='mergesort'
    )
    chosen = ranked.drop_duplicates([GROUP, OBSERVATION]).copy()

    # Candidate coverage is determined by whether the observation's candidate set
    # contains at least one positive reference candidate.
    coverage = frame.groupby([GROUP, OBSERVATION], sort=False)[TARGET].max().rename('has_positive_candidate')
    chosen = chosen.join(coverage, on=[GROUP, OBSERVATION])
    is_covered = chosen['has_positive_candidate'].to_numpy(dtype=bool)
    top1_correct = chosen[TARGET].to_numpy(dtype=bool)

    metrics.update({
        'observations': int(len(chosen)),
        'covered_observations': int(is_covered.sum()),
        'candidate_coverage': float(is_covered.mean()),
        'candidate_miss_rate': float((~is_covered).mean()),
        'top1_accuracy_covered': float(top1_correct[is_covered].mean()) if is_covered.any() else None,
        'top1_accuracy_all_observations': float(top1_correct.mean())
    })
    return metrics, chosen

print('Evaluation function ready.')

# 7. Five-fold GroupKFold experiment using the team's fixed fold assignments.
# A trip is entirely in one validation fold; its candidate rows never cross folds.
X = train[FEATURES].to_numpy(dtype=np.float32, copy=True)
y = train[TARGET].to_numpy(dtype=np.uint8, copy=True)
cv_rows = []
cv_feature_importances = []

for fold in range(1, 6):
    val_mask = (fold_id == fold)
    train_idx = np.flatnonzero(~val_mask)
    val_idx = np.flatnonzero(val_mask)

    train_trip_ids = set(train.iloc[train_idx][GROUP].unique())
    val_trip_ids = set(train.iloc[val_idx][GROUP].unique())
    assert train_trip_ids.isdisjoint(val_trip_ids), f'Trip leakage in fold {fold}'

    model = make_model(seed=RANDOM_STATE + fold)
    start = time.time()
    model.fit(X[train_idx], y[train_idx])
    fit_seconds = time.time() - start

    start = time.time()
    val_prob = model.predict_proba(X[val_idx])[:, 1]
    predict_seconds = time.time() - start

    metrics, _ = evaluate_predictions(train.iloc[val_idx], val_prob)
    metrics.update({
        'fold': fold,
        'train_trips': len(train_trip_ids),
        'validation_trips': len(val_trip_ids),
        'fit_seconds': fit_seconds,
        'predict_seconds': predict_seconds
    })
    cv_rows.append(metrics)
    cv_feature_importances.append(model.feature_importances_)

    print(
        f"Fold {fold}/5 | Macro-F1={metrics['candidate_macro_f1']:.4f} | "
        f"Top-1 covered={metrics['top1_accuracy_covered']:.4f} | "
        f"Coverage={metrics['candidate_coverage']:.4f} | "
        f"Fit={fit_seconds:.1f}s"
    )

cv_df = pd.DataFrame(cv_rows)
