"""Candidate-level binary MLP experiment with trip-grouped CV.

Input CSV contract: one row per (trip_id, observation_id, candidate arc), numeric
features, and binary `is_match`. No route labels are inferred by this module;
features and labels must be generated by the shared, documented alignment code.
The student-test CSV is evaluation only and is never used to fit scaling/weights.
"""
from __future__ import annotations

